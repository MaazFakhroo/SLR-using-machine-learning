    def create_gradient(self, width, height, color1, color2):
        """Create a vertical gradient image for the background"""
        gradient_img = tk.PhotoImage(width=width, height=height)
        
        r1, g1, b1 = self.hex_to_rgb(color1)
        r2, g2, b2 = self.hex_to_rgb(color2)
        
        for y in range(height):
            r = int(r1 + (r2 - r1) * y / height)
            g = int(g1 + (g2 - g1) * y / height)
            b = int(b1 + (b2 - b1) * y / height)
            
            color = f'#{r:02x}{g:02x}{b:02x}'
            row = "{" + " ".join(color for _ in range(width)) + "}"
            gradient_img.put(row, (0, y))
            
        return gradient_img
        
    def hex_to_rgb(self, hex_color):
        """Convert hex color to RGB values"""
        hex_color = hex_color.lstrip('#')
        return tuple(int(hex_color[i:i+2], 16) for i in (0, 2, 4))
    
    def create_styled_button(self, parent, x, y, bg_color, text="", width=150, height=40, command=None):
        """Create a styled button with hover effect"""
        button_frame = tk.Frame(parent, bg=bg_color, bd=0)
        button_frame.place(x=x, y=y, width=width, height=height)
        
        button = tk.Button(button_frame, text=text, font=("Helvetica", 14), fg="white", 
                          bg=bg_color, activebackground=self.lighten_color(bg_color),
                          relief="flat", bd=0, command=command)
        button.pack(fill=tk.BOTH, expand=True)
        
        # Add hover effect
        button.bind("<Enter>", lambda e: e.widget.config(bg=self.lighten_color(bg_color)))
        button.bind("<Leave>", lambda e: e.widget.config(bg=bg_color))
        
        return button
    
    def lighten_color(self, color):
        """Lighten a color for hover effect"""
        r, g, b = self.hex_to_rgb(color)
        # Lighten by 20%
        r = min(255, int(r + (255 - r) * 0.2))
        g = min(255, int(g + (255 - g) * 0.2))
        b = min(255, int(b + (255 - b) * 0.2))
        return f'#{r:02x}{g:02x}{b:02x}'

    def translate_text(self):
        input_text = self.translation_input.get("1.0", "end").strip()
        if not input_text:
            self.translated_output.delete("1.0", "end")
            self.translated_output.insert("1.0", "Please enter text to translate.")
            return

        prompt = f"Translate the following sentence to {self.lang_var.get()}:\n\n{input_text}"
        try:
            model = genai.GenerativeModel("models/gemini-1.5-flash-latest")
            response = model.generate_content(prompt)
            translated = response.text.strip()
            self.translated_output.delete("1.0", "end")
            self.translated_output.insert("1.0", translated)
        except Exception as e:
            self.translated_output.delete("1.0", "end")
            self.translated_output.insert("1.0", f"Error: {str(e)}")

